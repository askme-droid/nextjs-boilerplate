#!/usr/bin/env node
// Copies the directory's data from Postgres (Neon) into a SQL file that
// Cloudflare D1 can load.
//
//   1. Create the D1 tables (once):
//        npx wrangler d1 migrations apply DB --remote [--env staging]
//   2. Export from Neon (reads DATABASE_URL from .env.local or the shell):
//        node scripts/neon-to-d1.mjs
//      -> writes d1-import.sql (keep it private: it holds user accounts)
//   3. Load it into D1:
//        npx wrangler d1 execute DB --remote [--env staging] --file=d1-import.sql
//      (use --local instead of --remote for the copy `npm run dev` uses)
//
// The D1 tables and columns are read from migrations/*.sql, so only columns
// D1 has are copied. Values are converted to what the app expects on D1:
// timestamps -> milliseconds, true/false -> 1/0, lists and JSON -> JSON text,
// numbers like 25.90 -> "25.90".
//
// Login sessions and email-verification codes are NOT copied: everyone signs
// in again once, and no old session survives the move.
//
// The file starts by emptying the D1 tables, so running it again replaces
// the data instead of duplicating it.

import { readFileSync, readdirSync, writeFileSync, existsSync } from "node:fs";
import postgres from "postgres";

const OUT = process.argv[2] ?? "d1-import.sql";

// Same order as the foreign keys need (parents first).
const TABLES = [
  "user",
  "account",
  "categories",
  "experience_tags",
  "listings",
  "listing_images",
  "listing_experience_tags",
  "hero_slides",
];
const SKIPPED = ["session", "verification"];

function loadEnvFile() {
  if (process.env.DATABASE_URL || !existsSync(".env.local")) return;
  for (const line of readFileSync(".env.local", "utf8").split(/\r?\n/)) {
    const m = line.match(/^\s*DATABASE_URL\s*=\s*(.*)\s*$/);
    if (m) process.env.DATABASE_URL = m[1].replace(/^["']|["']$/g, "");
  }
}

/** D1 columns per table, from the CREATE TABLE statements in migrations/. */
function d1Columns() {
  const tables = new Map();
  const files = readdirSync("migrations").filter((f) => f.endsWith(".sql")).sort();
  for (const f of files) {
    const text = readFileSync(`migrations/${f}`, "utf8");
    for (const m of text.matchAll(/CREATE TABLE `(\w+)` \(([\s\S]*?)\n\);/g)) {
      const cols = new Map();
      for (const line of m[2].split("\n")) {
        const c = line.trim().match(/^`(\w+)` (\w+)/);
        if (c) cols.set(c[1], c[2].toLowerCase());
      }
      tables.set(m[1], cols);
    }
    for (const m of text.matchAll(/ALTER TABLE `(\w+)` ADD `(\w+)` (\w+)/g)) {
      tables.get(m[1])?.set(m[2], m[3].toLowerCase());
    }
  }
  return tables;
}

const quote = (s) => `'${String(s).replace(/'/g, "''")}'`;

function toSql(value, pgType, d1Type) {
  if (value === null || value === undefined) return "NULL";
  if (pgType === "date") return quote(value instanceof Date ? value.toISOString().slice(0, 10) : String(value).slice(0, 10));
  if (value instanceof Date) return d1Type === "integer" ? String(value.getTime()) : quote(value.toISOString());
  if (typeof value === "boolean") return value ? "1" : "0";
  if (typeof value === "number" || typeof value === "bigint") return String(value);
  if (pgType === "USER-DEFINED") {
    // pgvector prints as "[0.1,0.2,...]" - already a JSON array.
    return quote(String(value).replace(/\s+/g, ""));
  }
  if (Array.isArray(value) || (typeof value === "object" && value !== null)) return quote(JSON.stringify(value));
  if (pgType === "jsonb" || pgType === "json") return quote(typeof value === "string" ? value : JSON.stringify(value));
  if (d1Type === "integer" && /^-?\d+$/.test(String(value))) return String(value);
  return quote(value);
}

async function main() {
  loadEnvFile();
  const url = process.env.DATABASE_URL;
  if (!url) throw new Error("Set DATABASE_URL (the Neon link) in .env.local or the shell.");
  if (!existsSync("migrations")) throw new Error("Run this from the project folder (migrations/ not found).");

  const d1 = d1Columns();
  const sql = postgres(url, { max: 1, prepare: false });
  const lines = [
    "-- FDSG directory data for Cloudflare D1, exported " + new Date().toISOString(),
    "-- Generated by scripts/neon-to-d1.mjs. Contains user accounts: keep private, delete after loading.",
    "PRAGMA defer_foreign_keys = true;",
  ];
  // Empty the tables first, children before parents (and the skipped ones).
  for (const t of [...SKIPPED, ...TABLES].reverse()) if (d1.has(t)) lines.push(`DELETE FROM \`${t}\`;`);

  const counts = {};
  try {
    for (const table of TABLES) {
      const d1Cols = d1.get(table);
      if (!d1Cols) throw new Error(`D1 has no table "${table}" - check migrations/.`);
      const pgCols = await sql`
        select column_name, data_type from information_schema.columns
        where table_schema = 'public' and table_name = ${table}`;
      const pgType = new Map(pgCols.map((c) => [c.column_name, c.data_type]));
      const cols = [...d1Cols.keys()].filter((c) => pgType.has(c));
      const missing = [...d1Cols.keys()].filter((c) => !pgType.has(c));
      if (missing.length) console.warn(`  ${table}: not in Neon, left empty/default: ${missing.join(", ")}`);

      // Read vectors and dates as text: a date would otherwise come back as a
      // JavaScript Date at midnight, shifted by the time zone.
      const asText = new Set(["USER-DEFINED", "date"]);
      const select = cols
        .map((c) => (asText.has(pgType.get(c)) ? `"${c}"::text as "${c}"` : `"${c}"`))
        .join(", ");
      const rows = await sql.unsafe(`select ${select} from "${table}"`);
      counts[table] = rows.length;
      const colList = cols.map((c) => `\`${c}\``).join(", ");
      for (const row of rows) {
        const values = cols.map((c) => toSql(row[c], pgType.get(c), d1Cols.get(c))).join(", ");
        lines.push(`INSERT INTO \`${table}\` (${colList}) VALUES (${values});`);
      }
    }
  } finally {
    await sql.end();
  }

  writeFileSync(OUT, lines.join("\n") + "\n");
  console.log(`Wrote ${OUT}:`);
  for (const [t, n] of Object.entries(counts)) console.log(`  ${t.padEnd(24)} ${n}`);
  console.log(`  (not copied: ${SKIPPED.join(", ")} - everyone signs in again)`);
}

main().catch((e) => {
  console.error(e instanceof Error ? e.message : e);
  process.exit(1);
});
